import test from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { openTeamsStore } from "../dist/teams-store.js";
import { teamsDeliveryApi } from "../dist/teams-delivery-api.js";
import type { TeamsSender } from "../dist/teams-reply-port.js";
import type { AppContext } from "../dist/application/context.js";

test("delivery evidence listing is read-only; explicit source recheck never confirms or resends an unknown delivery", async t => {
  const dir = await mkdtemp(join(tmpdir(), "teams-delivery-evidence-"));
  const store = openTeamsStore(dir);
  t.after(async () => { store.close(); await rm(dir, { recursive: true, force: true }); });
  store.record({ id: "chat:source", chatId: "chat", chatType: "oneOnOne", senderId: "peer", senderName: "Peer", direction: "in", text: "private frozen source", createdAt: new Date().toISOString(), important: true, notificationPriority: "urgent" });
  const batch = store.notifications.create(false, () => ({ text: "private frozen body", prompt: "private prompt" }))!;
  const epoch = Number(store.notifications.claim(batch.id)); store.notifications.beginExternal(batch.id, epoch); store.notifications.unknown(batch.id, epoch);
  let reads = 0, sends = 0, fail = false, edited = false;
  const sender: TeamsSender = { send: async () => { sends++; }, read: async () => {
    reads++; if (fail) throw new Error("credential secret");
    return { data: { id: "source", chatId: "chat", body: { contentType: "text", content: edited ? "changed" : "private frozen source" } } } as never;
  } };
  const context = { teamsStore: store, teamsSender: sender, config: { offline: false } as AppContext["config"] };
  const url = new URL("http://local/api/teams/delivery-issues");
  const listed = await teamsDeliveryApi(context, "GET", url, {});
  assert.equal(reads, 0); assert.doesNotMatch(JSON.stringify(listed), /private frozen|private prompt/);
  assert.match(JSON.stringify(listed), /unknown/);
  const recheck = new URL(url + "/recheck");
  const result = await teamsDeliveryApi(context, "POST", recheck, { id: batch.id });
  assert.equal((result!.data as { deliveryCheck: string }).deliveryCheck, "unconfirmed");
  assert.equal((result!.data as { sourceCheck: string }).sourceCheck, "verified");
  edited = true;
  const changed = await teamsDeliveryApi(context, "POST", recheck, { id: batch.id });
  assert.equal((changed!.data as { sourceCheck: string }).sourceCheck, "invalidated");
  fail = true;
  await assert.rejects(teamsDeliveryApi(context, "POST", recheck, { id: batch.id }), error => error instanceof Error && !error.message.includes("credential secret"));
  assert.equal(sends, 0); assert.equal(store.notifications.deliveryIssues().items[0].state, "unknown");
  assert.equal(store.notifications.claim(batch.id), false);
  context.config.offline = true;
  const before = reads;
  await assert.rejects(teamsDeliveryApi(context, "POST", recheck, { id: batch.id }), /未连接/);
  assert.equal(reads, before);
  context.config.offline = false;
  await assert.rejects(teamsDeliveryApi(context, "POST", recheck, { id: "../invalid" }), /编号无效/);
  store.revokeMessage("chat", "chat:source");
  const revoked = await teamsDeliveryApi(context, "POST", recheck, { id: batch.id });
  assert.equal((revoked!.data as { sourceCheck: string }).sourceCheck, "invalidated");
  assert.equal(reads, before, "known revoked source is never fetched or resurrected");
  assert.equal(sends, 0);
});
